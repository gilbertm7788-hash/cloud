def classify(title: str) -> str:
    """제목에서 분야를 고른다. 걸리는 규칙이 없으면 '업계 일반'."""
    if not title:
        return DEFAULT_TOPIC
    for topic, keywords in TOPIC_RULES:
        if any(k in title for k in keywords):
            return topic
    return DEFAULT_TOPIC


def topic_order() -> list[str]:
    """다이제스트에 노출할 분야 순서 (규칙 순서 + 기타는 맨 뒤)."""
